#!/usr/bin/env node
/**
 * scripts/get-supabase-env.js
 * Single-command utility to inspect, display, and auto-generate all required
 * environment variables for both Frontend and Backend from Supabase.
 *
 * Usage:
 *   npm run supabase:vars           # Displays all required variables
 *   npm run supabase:vars -- --write # Writes them directly to backend/.env and frontend/.env
 */

import { execSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const shouldWrite = process.argv.includes("--write");

console.log("==================================================================");
console.log(" ⚡ NEXUS-OPS SUPABASE ENVIRONMENT & MIGRATION INSPECTOR");
console.log("==================================================================");

let supabaseUrl = "https://your-project-id.supabase.co";
let anonKey = "your-supabase-anon-key";
let serviceRoleKey = "your-supabase-service-role-key";
let isLocal = false;

// 1. Try checking if local Supabase CLI is active
try {
  const statusOutput = execSync("npx.cmd supabase status -o json", {
    cwd: rootDir,
    encoding: "utf-8",
    stdio: ["pipe", "pipe", "ignore"]
  });

  if (statusOutput) {
    const parsed = JSON.parse(statusOutput);
    if (parsed.API_URL) {
      supabaseUrl = parsed.API_URL;
      anonKey = parsed.ANON_KEY;
      serviceRoleKey = parsed.SERVICE_ROLE_KEY;
      isLocal = true;
      console.log(" [✓] Detected Active Local Supabase CLI Instance!");
    }
  }
} catch (e) {
  // Local supabase not running or docker not active - check existing backend/.env
}

// 2. Read existing backend/.env if populated
const backendEnvPath = path.join(rootDir, "backend", ".env");
if (fs.existsSync(backendEnvPath) && !isLocal) {
  const content = fs.readFileSync(backendEnvPath, "utf-8");
  const matchUrl = content.match(/^SUPABASE_URL=(.*)$/m);
  const matchAnon = content.match(/^SUPABASE_ANON_KEY=(.*)$/m);
  const matchService = content.match(/^SUPABASE_SERVICE_ROLE_KEY=(.*)$/m);

  if (matchUrl && matchUrl[1].trim() && !matchUrl[1].includes("your-project-id")) {
    supabaseUrl = matchUrl[1].trim();
  }
  if (matchAnon && matchAnon[1].trim() && !matchAnon[1].includes("your-supabase")) {
    anonKey = matchAnon[1].trim();
  }
  if (matchService && matchService[1].trim() && !matchService[1].includes("your-supabase")) {
    serviceRoleKey = matchService[1].trim();
  }
}

console.log("\n📦 REQUIRED VARIABLES FOR BACKEND (backend/.env):");
console.log("------------------------------------------------------------------");
console.log(`PORT=5000`);
console.log(`NODE_ENV=development`);
console.log(`SUPABASE_URL=${supabaseUrl}`);
console.log(`SUPABASE_ANON_KEY=${anonKey}`);
console.log(`SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`);
console.log(`SUPABASE_SCHEMA=public`);
console.log(`GEMINI_API_KEY=`);
console.log(`LLM_MODEL=gemini-2.5-flash`);

console.log("\n🌐 REQUIRED VARIABLES FOR FRONTEND (frontend/.env):");
console.log("------------------------------------------------------------------");
console.log(`VITE_SUPABASE_URL=${supabaseUrl}`);
console.log(`VITE_SUPABASE_ANON_KEY=${anonKey}`);
console.log(`VITE_API_BASE_URL=/api`);
console.log(`VITE_APP_ENV=development`);

console.log("\n💾 SQL DATABASE COMMAND (Execute in Supabase SQL Editor):");
console.log("------------------------------------------------------------------");
console.log("SELECT * FROM public.get_required_env_variables();");

if (shouldWrite) {
  const backendContent = `# Auto-generated by npm run supabase:vars -- --write
PORT=5000
NODE_ENV=development

SUPABASE_URL=${supabaseUrl}
SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}
SUPABASE_SCHEMA=public

GEMINI_API_KEY=
LLM_MODEL=gemini-2.5-flash
`;

  const frontendContent = `# Auto-generated by npm run supabase:vars -- --write
VITE_SUPABASE_URL=${supabaseUrl}
VITE_SUPABASE_ANON_KEY=${anonKey}
VITE_API_BASE_URL=/api
VITE_APP_ENV=development
`;

  fs.writeFileSync(path.join(rootDir, "backend", ".env"), backendContent, "utf-8");
  fs.writeFileSync(path.join(rootDir, "frontend", ".env"), frontendContent, "utf-8");
  console.log("\n [✓] Successfully wrote variables directly to backend/.env and frontend/.env!");
} else {
  console.log("\n💡 TIP: Run 'npm run supabase:vars -- --write' to auto-save these to .env files.");
}
console.log("==================================================================\n");
